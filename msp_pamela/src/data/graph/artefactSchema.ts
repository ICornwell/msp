import { createSchema } from 'msp_common';

export const artefactSchema = createSchema('artefact')
  .withFQId({ namespace: 'pamela', version: '1.0' })
  .withProperty('name')
    .forType<string>()
    .withDictionaryId('pamela-artefact-name', '1.0')
    .withInfoType('Text')
    .withDefaultLabel('Name')
    .endProperty()
  .withProperty('kind')
    .forType<string>()
    .withDictionaryId('pamela-artefact-kind', '1.0')
    .withInfoType('Text')
    .withDefaultLabel('Kind')
    .endProperty()
  .withProperty('description')
    .forType<string>()
    .withDictionaryId('pamela-artefact-description', '1.0')
    .withInfoType('Text')
    .withDefaultLabel('Description')
    .endProperty()
  .withProperty('context')
    .forType<string>()
    .withDictionaryId('pamela-artefact-context', '1.0')
    .withInfoType('Text')
    .withDefaultLabel('Context')
    .endProperty()
  .withProperty('provenance')
    .forType<string>()
    .withDictionaryId('pamela-artefact-provenance', '1.0')
    .withInfoType('Text')
    .withDefaultLabel('Provenance')
    .endProperty()
  .buildSchema();
