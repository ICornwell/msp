import { createSchema } from 'msp_common';
import { artefactSchema } from './artefactSchema.js';

export const assertionSchema = createSchema('assertion')
  .withFQId({ namespace: 'pamela', version: '1.0' })
  .inheritsFrom(artefactSchema)
  .withProperty('subject')
    .forType<string>()
    .withDictionaryId('pamela-assertion-subject', '1.0')
    .withInfoType('Text')
    .withDefaultLabel('Subject')
    .endProperty()
  .withProperty('predicate')
    .forType<string>()
    .withDictionaryId('pamela-assertion-predicate', '1.0')
    .withInfoType('Text')
    .withDefaultLabel('Predicate')
    .endProperty()
  .withProperty('object')
    .forType<string>()
    .withDictionaryId('pamela-assertion-object', '1.0')
    .withInfoType('Text')
    .withDefaultLabel('Object')
    .endProperty()
  .withProperty('polarity')
    .forType<string>()
    .withDictionaryId('pamela-assertion-polarity', '1.0')
    .withInfoType('Text')
    .withDefaultLabel('Polarity')
    .endProperty()
  .buildSchema();
