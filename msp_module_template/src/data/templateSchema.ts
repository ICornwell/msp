import { createSchema } from 'msp_common';

export const exampleSchema = createSchema('example')
  .withFQId({ namespace: 'module_template', version: '1.0' })
  .withProperty('name')
    .forType<string>()
    .withDictionaryId('module_template-name', '1.0')
    .withInfoType('Text')
    .withDefaultLabel('Name')
    .endProperty()
  .withProperty('kind')
    .forType<string>()
    .withDictionaryId('module_template-kind', '1.0')
    .withInfoType('Text')
    .withDefaultLabel('Kind')
    .endProperty()
  .withProperty('description')
    .forType<string>()
    .withDictionaryId('module_template-description', '1.0')
    .withInfoType('Text')
    .withDefaultLabel('Description')
    .endProperty()
  .withProperty('context')
    .forType<string>()
    .withDictionaryId('module_template-context', '1.0')
    .withInfoType('Text')
    .withDefaultLabel('Context')
    .endProperty()
  .withProperty('provenance')
    .forType<string>()
    .withDictionaryId('module_template-provenance', '1.0')
    .withInfoType('Text')
    .withDefaultLabel('Provenance')
    .endProperty()
  .buildSchema();
