import { createSchema } from 'msp_common';
import { exampleSchema } from './templateSchema.js';

export const exampleOtherSchema = createSchema('exampleOther')
  .withFQId({ namespace: 'module_template', version: '1.0' })
  .inheritsFrom(exampleSchema)
  .withProperty('subject')
    .forType<string>()
    .withDictionaryId('module_template-assertion-subject', '1.0')
    .withInfoType('Text')
    .withDefaultLabel('Subject')
    .endProperty()
  .withProperty('predicate')
    .forType<string>()
    .withDictionaryId('module_template-assertion-predicate', '1.0')
    .withInfoType('Text')
    .withDefaultLabel('Predicate')
    .endProperty()
  .withProperty('object')
    .forType<string>()
    .withDictionaryId('module_template-assertion-object', '1.0')
    .withInfoType('Text')
    .withDefaultLabel('Object')
    .endProperty()
  .withProperty('polarity')
    .forType<string>()
    .withDictionaryId('module_template-assertion-polarity', '1.0')
    .withInfoType('Text')
    .withDefaultLabel('Polarity')
    .endProperty()
  .buildSchema();
